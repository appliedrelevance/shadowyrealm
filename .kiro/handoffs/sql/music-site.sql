-- Schema for the Music site (key "music"), generated by tools/site-schema.ts
-- from src/sites/music.ts. A structural copy of shadowyrealm after migration
-- 20261107000827, without credit_shares(); only the enums and the dimension columns differ,
-- and a site that counts people adds head-count columns.

create schema music;
alter schema music owner to postgres;

create type music.entity_type as enum ('person', 'group', 'style', 'work', 'instrument');
create type music.publication_status as enum ('draft', 'submitted', 'under_review', 'published', 'archived');
create type music.relationship_type as enum ('genre', 'gave_rise', 'member', 'made', 'influence');

create or replace function music.update_updated_at() returns trigger
    language plpgsql
    as $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;
alter function music.update_updated_at() owner to postgres;

-- ---------- Tables ----------

create table music.entities (
  id bigint generated always as identity constraint entities_pkey primary key,
  slug text not null,
  name text not null,
  entity_type music.entity_type not null,
  description text not null,
  biography text,
  image_url text,
  status music.publication_status not null default 'draft',
  metadata jsonb,
  ai_generated_content boolean not null default false,
  created_by uuid not null constraint entities_created_by_fkey references auth.users (id),
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);

create table music.assessment_periods (
  id bigint generated always as identity constraint assessment_periods_pkey primary key,
  entity_id bigint not null constraint assessment_periods_entity_id_fkey references music.entities (id) on delete cascade,
  label text not null,
  start_year integer not null,
  end_year integer not null,
  description text,
  reach_factor integer not null default 5 constraint assessment_periods_reach_factor_check check (reach_factor >= 1 and reach_factor <= 10),
  persistence_factor integer not null default 5 constraint assessment_periods_persistence_factor_check check (persistence_factor >= 1 and persistence_factor <= 10),
  geographic_scope text not null default 'national'::text,
  created_by uuid not null constraint assessment_periods_created_by_fkey references auth.users (id),
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint valid_year_range check (end_year >= start_year)
);

create table music.assessments (
  id bigint generated always as identity constraint assessments_pkey primary key,
  entity_id bigint not null constraint assessments_entity_id_fkey references music.entities (id) on delete cascade,
  period_id bigint constraint assessments_period_id_fkey references music.assessment_periods (id) on delete set null,
  feeling_benefit numeric(4,2) not null constraint assessments_feeling_benefit_check check (feeling_benefit between 0 and 10),
  feeling_harm numeric(4,2) not null constraint assessments_feeling_harm_check check (feeling_harm between 0 and 10),
  feeling_justification text not null constraint assessments_feeling_justification_check check (feeling_justification <> ''),
  devotion_benefit numeric(4,2) not null constraint assessments_devotion_benefit_check check (devotion_benefit between 0 and 10),
  devotion_harm numeric(4,2) not null constraint assessments_devotion_harm_check check (devotion_harm between 0 and 10),
  devotion_justification text not null constraint assessments_devotion_justification_check check (devotion_justification <> ''),
  gathering_benefit numeric(4,2) not null constraint assessments_gathering_benefit_check check (gathering_benefit between 0 and 10),
  gathering_harm numeric(4,2) not null constraint assessments_gathering_harm_check check (gathering_harm between 0 and 10),
  gathering_justification text not null constraint assessments_gathering_justification_check check (gathering_justification <> ''),
  memory_benefit numeric(4,2) not null constraint assessments_memory_benefit_check check (memory_benefit between 0 and 10),
  memory_harm numeric(4,2) not null constraint assessments_memory_harm_check check (memory_harm between 0 and 10),
  memory_justification text not null constraint assessments_memory_justification_check check (memory_justification <> ''),
  sources text[],
  confidence_level numeric(3,2) default 0.5 constraint assessments_confidence_level_check check (confidence_level >= 0 and confidence_level <= 1),
  controversy_level numeric(3,2) default 0.0 constraint assessments_controversy_level_check check (controversy_level >= 0 and controversy_level <= 1),
  ai_suggested boolean not null default false,
  ai_model_used text,
  bias_warnings text[],
  created_by uuid not null constraint assessments_created_by_fkey references auth.users (id),
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  evidence text
);

create table music.relationships (
  id bigint generated always as identity constraint relationships_pkey primary key,
  source_entity_id bigint not null constraint relationships_source_entity_id_fkey references music.entities (id) on delete cascade,
  target_entity_id bigint not null constraint relationships_target_entity_id_fkey references music.entities (id) on delete cascade,
  relationship_type music.relationship_type not null,
  description text not null,
  strength numeric(5,4) not null default 0.5 constraint relationships_strength_check check (strength >= 0 and strength <= 1),
  temporal_overlap numeric(3,2) default 0.5 constraint relationships_temporal_overlap_check check (temporal_overlap >= 0 and temporal_overlap <= 1),
  created_by uuid not null constraint relationships_created_by_fkey references auth.users (id),
  created_at timestamp with time zone not null default now(),
  constraint no_self_relationship check (source_entity_id <> target_entity_id),
  constraint unique_relationship unique (source_entity_id, target_entity_id, relationship_type)
);

create table music.entity_audit_log (
  id bigint generated always as identity constraint entity_audit_log_pkey primary key,
  entity_id bigint not null constraint entity_audit_log_entity_id_fkey references music.entities (id) on delete cascade,
  action text not null,
  old_value jsonb,
  new_value jsonb,
  performed_by uuid not null constraint entity_audit_log_performed_by_fkey references auth.users (id),
  performed_at timestamp with time zone not null default now()
);

alter table music.entities owner to postgres;
alter table music.assessment_periods owner to postgres;
alter table music.assessments owner to postgres;
alter table music.relationships owner to postgres;
alter table music.entity_audit_log owner to postgres;

-- ---------- Indexes ----------

create index assessments_creator_idx on music.assessments using btree (created_by);
create index assessments_entity_idx on music.assessments using btree (entity_id, created_at desc);
create index assessments_period_idx on music.assessments using btree (period_id);
create index audit_entity_idx on music.entity_audit_log using btree (entity_id, performed_at desc);
create index entities_creator_idx on music.entities using btree (created_by);
create index entities_metadata_idx on music.entities using gin (metadata) where (metadata is not null);
create index entities_slug_idx on music.entities using btree (slug);
create unique index entities_slug_published_uniq on music.entities using btree (slug) where (status = 'published'::music.publication_status);
create index entities_status_idx on music.entities using btree (status, created_at desc);
create index entities_type_idx on music.entities using btree (entity_type, status);
create index periods_entity_idx on music.assessment_periods using btree (entity_id, start_year);
create index relationships_source_idx on music.relationships using btree (source_entity_id);
create index relationships_target_idx on music.relationships using btree (target_entity_id);

-- ---------- Triggers ----------

create or replace trigger assessments_updated_at before update on music.assessments for each row execute function music.update_updated_at();
create or replace trigger entities_updated_at before update on music.entities for each row execute function music.update_updated_at();
create or replace trigger periods_updated_at before update on music.assessment_periods for each row execute function music.update_updated_at();

-- ---------- Row-level security ----------
-- The Worker writes as service_role, which bypasses RLS. Anyone may read
-- published entities, and child rows only of published entities.

alter table music.entities enable row level security;
alter table music.assessment_periods enable row level security;
alter table music.assessments enable row level security;
alter table music.relationships enable row level security;
alter table music.entity_audit_log enable row level security;

create policy entities_select_published on music.entities for select
  using (status = 'published'::music.publication_status);
create policy entities_select_own_drafts on music.entities for select to authenticated
  using (created_by = auth.uid() and status <> 'published'::music.publication_status);
create policy assessments_select on music.assessments for select
  using (exists (select 1 from music.entities e where e.id = entity_id and e.status = 'published'));
create policy periods_select on music.assessment_periods for select
  using (exists (select 1 from music.entities e where e.id = entity_id and e.status = 'published'));
create policy audit_select on music.entity_audit_log for select
  using (exists (select 1 from music.entities e where e.id = entity_id and e.status = 'published'));
create policy relationships_select on music.relationships for select
  using (
    exists (select 1 from music.entities e where e.id = source_entity_id and e.status = 'published')
    and exists (select 1 from music.entities e where e.id = target_entity_id and e.status = 'published')
  );

-- ---------- Grants ----------
-- Signed-in users of the shared project read only; the Worker writes.

grant usage on schema music to anon, authenticated, service_role;

grant select on all tables in schema music to anon;
grant all on all tables in schema music to authenticated, service_role;
revoke insert, update, delete, truncate, references, trigger on all tables in schema music from authenticated;

grant select on all sequences in schema music to anon, authenticated;
grant select, usage on all sequences in schema music to service_role;

alter default privileges for role postgres in schema music grant select on tables to anon;
alter default privileges for role postgres in schema music grant all on tables to authenticated, service_role;
alter default privileges for role postgres in schema music
  revoke insert, update, delete, truncate, references, trigger on tables from authenticated;
alter default privileges for role postgres in schema music grant select on sequences to anon, authenticated;
alter default privileges for role postgres in schema music grant select, usage on sequences to service_role;
