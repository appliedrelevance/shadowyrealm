/**
 * Prints the complete DDL for one site's schema (site-platform Requirement 5).
 *
 *   bun tools/site-schema.ts inventions > supabase/migrations/<version>_inventions_site.sql
 *
 * The output is a structural copy of the shadowyrealm schema as it stands
 * after monorepo migrations 20260810120000_baseline and
 * 20261107000827_shadowyrealm_influence_graph: the same tables, columns,
 * constraints, indexes, triggers, row-level security, policies, grants and
 * credit_shares. Only four things come from the site config: the schema name,
 * the entity_type and relationship_type enum values, the dimension columns of
 * assessments, and the link types credit_shares walks.
 *
 * `bun tools/site-schema.ts shadowyrealm` reproduces the live shadowyrealm
 * schema; tools/site-schema-check.sh proves it by comparing catalogs.
 *
 * Exposing the schema through the Data API is a separate step, because it
 * names every exposed schema at once; the handoff does it.
 */
import { siteFor } from "../src/sites";
import type { SiteConfig } from "../src/sites/types";

function literals(values: readonly string[]): string {
  return values.map((v) => `'${v.replace(/'/g, "''")}'`).join(", ");
}

export function siteSchemaDdl(site: SiteConfig): string {
  const s = site.schema;
  const dims = site.scoring.dimensions.map((d) => d.key);
  const credit = site.linkTypes.filter((t) => t.credit).map((t) => t.key);

  const dimensionColumns = dims
    .flatMap((d) => [
      `  ${d}_benefit numeric(4,2) not null constraint assessments_${d}_benefit_check check (${d}_benefit between 0 and 10),`,
      `  ${d}_harm numeric(4,2) not null constraint assessments_${d}_harm_check check (${d}_harm between 0 and 10),`,
      `  ${d}_justification text not null constraint assessments_${d}_justification_check check (${d}_justification <> ''),`,
    ])
    .join("\n");

  return `-- Schema for the ${site.brand.name} site (key "${site.key}"), generated by tools/site-schema.ts
-- from src/sites/${site.key}.ts. A structural copy of shadowyrealm after migration
-- 20261107000827; only the enums, the dimension columns and the credit link types differ.

create schema ${s};
alter schema ${s} owner to postgres;

create type ${s}.entity_type as enum (${literals(site.entityTypes.map((t) => t.key))});
create type ${s}.publication_status as enum ('draft', 'submitted', 'under_review', 'published', 'archived');
create type ${s}.relationship_type as enum (${literals(site.linkTypes.map((t) => t.key))});

create or replace function ${s}.update_updated_at() returns trigger
    language plpgsql
    as $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;
alter function ${s}.update_updated_at() owner to postgres;

-- ---------- Tables ----------

create table ${s}.entities (
  id bigint generated always as identity constraint entities_pkey primary key,
  slug text not null,
  name text not null,
  entity_type ${s}.entity_type not null,
  description text not null,
  biography text,
  image_url text,
  status ${s}.publication_status not null default 'draft',
  metadata jsonb,
  ai_generated_content boolean not null default false,
  created_by uuid not null constraint entities_created_by_fkey references auth.users (id),
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);

create table ${s}.assessment_periods (
  id bigint generated always as identity constraint assessment_periods_pkey primary key,
  entity_id bigint not null constraint assessment_periods_entity_id_fkey references ${s}.entities (id) on delete cascade,
  label text not null,
  start_year integer not null,
  end_year integer not null,
  description text,
  reach_factor integer not null default 5 constraint assessment_periods_reach_factor_check check (reach_factor >= 1 and reach_factor <= 10),
  persistence_factor integer not null default 5 constraint assessment_periods_persistence_factor_check check (persistence_factor >= 1 and persistence_factor <= 10),
  geographic_scope text not null default 'national'::text,
  created_by uuid not null constraint assessment_periods_created_by_fkey references auth.users (id),
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint valid_year_range check (end_year >= start_year)
);

create table ${s}.assessments (
  id bigint generated always as identity constraint assessments_pkey primary key,
  entity_id bigint not null constraint assessments_entity_id_fkey references ${s}.entities (id) on delete cascade,
  period_id bigint constraint assessments_period_id_fkey references ${s}.assessment_periods (id) on delete set null,
${dimensionColumns}
  sources text[],
  confidence_level numeric(3,2) default 0.5 constraint assessments_confidence_level_check check (confidence_level >= 0 and confidence_level <= 1),
  controversy_level numeric(3,2) default 0.0 constraint assessments_controversy_level_check check (controversy_level >= 0 and controversy_level <= 1),
  ai_suggested boolean not null default false,
  ai_model_used text,
  bias_warnings text[],
  created_by uuid not null constraint assessments_created_by_fkey references auth.users (id),
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);

create table ${s}.relationships (
  id bigint generated always as identity constraint relationships_pkey primary key,
  source_entity_id bigint not null constraint relationships_source_entity_id_fkey references ${s}.entities (id) on delete cascade,
  target_entity_id bigint not null constraint relationships_target_entity_id_fkey references ${s}.entities (id) on delete cascade,
  relationship_type ${s}.relationship_type not null,
  description text not null,
  strength numeric(3,2) not null default 0.5 constraint relationships_strength_check check (strength >= 0 and strength <= 1),
  temporal_overlap numeric(3,2) default 0.5 constraint relationships_temporal_overlap_check check (temporal_overlap >= 0 and temporal_overlap <= 1),
  created_by uuid not null constraint relationships_created_by_fkey references auth.users (id),
  created_at timestamp with time zone not null default now(),
  constraint no_self_relationship check (source_entity_id <> target_entity_id),
  constraint unique_relationship unique (source_entity_id, target_entity_id, relationship_type)
);

create table ${s}.entity_audit_log (
  id bigint generated always as identity constraint entity_audit_log_pkey primary key,
  entity_id bigint not null constraint entity_audit_log_entity_id_fkey references ${s}.entities (id) on delete cascade,
  action text not null,
  old_value jsonb,
  new_value jsonb,
  performed_by uuid not null constraint entity_audit_log_performed_by_fkey references auth.users (id),
  performed_at timestamp with time zone not null default now()
);

alter table ${s}.entities owner to postgres;
alter table ${s}.assessment_periods owner to postgres;
alter table ${s}.assessments owner to postgres;
alter table ${s}.relationships owner to postgres;
alter table ${s}.entity_audit_log owner to postgres;

-- ---------- Indexes ----------

create index assessments_creator_idx on ${s}.assessments using btree (created_by);
create index assessments_entity_idx on ${s}.assessments using btree (entity_id, created_at desc);
create index assessments_period_idx on ${s}.assessments using btree (period_id);
create index audit_entity_idx on ${s}.entity_audit_log using btree (entity_id, performed_at desc);
create index entities_creator_idx on ${s}.entities using btree (created_by);
create index entities_metadata_idx on ${s}.entities using gin (metadata) where (metadata is not null);
create index entities_slug_idx on ${s}.entities using btree (slug);
create unique index entities_slug_published_uniq on ${s}.entities using btree (slug) where (status = 'published'::${s}.publication_status);
create index entities_status_idx on ${s}.entities using btree (status, created_at desc);
create index entities_type_idx on ${s}.entities using btree (entity_type, status);
create index periods_entity_idx on ${s}.assessment_periods using btree (entity_id, start_year);
create index relationships_source_idx on ${s}.relationships using btree (source_entity_id);
create index relationships_target_idx on ${s}.relationships using btree (target_entity_id);

-- ---------- Triggers ----------

create or replace trigger assessments_updated_at before update on ${s}.assessments for each row execute function ${s}.update_updated_at();
create or replace trigger entities_updated_at before update on ${s}.entities for each row execute function ${s}.update_updated_at();
create or replace trigger periods_updated_at before update on ${s}.assessment_periods for each row execute function ${s}.update_updated_at();

-- ---------- Credit shares ----------
-- Links point from cause to consequence. ${credit.join(", ")} carry credit; the
-- other link types describe. A chain's share is the product of its strengths, and
-- a pair's share is its strongest chain. Chains are cut once their share falls
-- below 0.001, which bounds the walk on dense graphs.

create function ${s}.credit_shares(published_only boolean default true)
returns table (ancestor_id bigint, descendant_id bigint, share numeric)
language sql
stable
set search_path = ''
as $$
  with recursive edges as (
    select r.source_entity_id as source, r.target_entity_id as target, r.strength::numeric as strength
    from ${s}.relationships r
    join ${s}.entities s on s.id = r.source_entity_id
    join ${s}.entities t on t.id = r.target_entity_id
    where r.relationship_type in (${literals(credit)})
      and r.strength > 0
      and (not published_only or (s.status = 'published' and t.status = 'published'))
  ),
  walk (ancestor_id, descendant_id, share) as (
    select source, target, strength from edges
    union all
    select w.ancestor_id, e.target, w.share * e.strength
    from walk w
    join edges e on e.source = w.descendant_id
    where w.share * e.strength >= 0.001
  ) cycle descendant_id set is_cycle using path
  select w.ancestor_id, w.descendant_id, max(w.share)
  from walk w
  where not w.is_cycle and w.ancestor_id <> w.descendant_id
  group by w.ancestor_id, w.descendant_id
$$;
alter function ${s}.credit_shares(boolean) owner to postgres;
revoke all on function ${s}.credit_shares(boolean) from public, anon, authenticated;
grant execute on function ${s}.credit_shares(boolean) to service_role;

-- ---------- Row-level security ----------
-- The Worker writes as service_role, which bypasses RLS. Anyone may read
-- published entities, and child rows only of published entities.

alter table ${s}.entities enable row level security;
alter table ${s}.assessment_periods enable row level security;
alter table ${s}.assessments enable row level security;
alter table ${s}.relationships enable row level security;
alter table ${s}.entity_audit_log enable row level security;

create policy entities_select_published on ${s}.entities for select
  using (status = 'published'::${s}.publication_status);
create policy entities_select_own_drafts on ${s}.entities for select to authenticated
  using (created_by = auth.uid() and status <> 'published'::${s}.publication_status);
create policy assessments_select on ${s}.assessments for select
  using (exists (select 1 from ${s}.entities e where e.id = entity_id and e.status = 'published'));
create policy periods_select on ${s}.assessment_periods for select
  using (exists (select 1 from ${s}.entities e where e.id = entity_id and e.status = 'published'));
create policy audit_select on ${s}.entity_audit_log for select
  using (exists (select 1 from ${s}.entities e where e.id = entity_id and e.status = 'published'));
create policy relationships_select on ${s}.relationships for select
  using (
    exists (select 1 from ${s}.entities e where e.id = source_entity_id and e.status = 'published')
    and exists (select 1 from ${s}.entities e where e.id = target_entity_id and e.status = 'published')
  );

-- ---------- Grants ----------
-- Signed-in users of the shared project read only; the Worker writes.

grant usage on schema ${s} to anon, authenticated, service_role;

grant select on all tables in schema ${s} to anon;
grant all on all tables in schema ${s} to authenticated, service_role;
revoke insert, update, delete, truncate, references, trigger on all tables in schema ${s} from authenticated;

grant select on all sequences in schema ${s} to anon, authenticated;
grant select, usage on all sequences in schema ${s} to service_role;

alter default privileges for role postgres in schema ${s} grant select on tables to anon;
alter default privileges for role postgres in schema ${s} grant all on tables to authenticated, service_role;
alter default privileges for role postgres in schema ${s}
  revoke insert, update, delete, truncate, references, trigger on tables from authenticated;
alter default privileges for role postgres in schema ${s} grant select on sequences to anon, authenticated;
alter default privileges for role postgres in schema ${s} grant select, usage on sequences to service_role;
`;
}

if (import.meta.main) {
  const key = process.argv[2];
  process.stdout.write(siteSchemaDdl(siteFor(key)));
}
